"""Subset Noto Serif SC into src/fonts.css so law text looks the same on every computer.

Maintenance tool, run only when the law text or interface wording changes:

    python3 build_font.py NotoSerifSC-Regular.otf NotoSerifSC-SemiBold.otf

Requires fontTools and brotli (pip install fonttools brotli). The source fonts are not
kept in the project. The character set comes from material shared by both editions
(law text, 条旨, the guide and interface wording), never from personal notes, so the
debug and pure editions can use the same src/fonts.css. build.py inlines the file
when it exists; without it the page falls back to the system serif. The copyright
notice and full license text travel with the font in src/OFL.txt.
"""
from pathlib import Path
import base64
import io
import json
import re
import sys

from fontTools import subset
from fontTools.ttLib import TTFont

root = Path(__file__).resolve().parent


def strings(value):
    if isinstance(value, str):
        yield value
    elif isinstance(value, dict):
        for item in value.values():
            yield from strings(item)
    elif isinstance(value, list):
        for item in value:
            yield from strings(item)


def charset():
    text = []
    # Every data pack under codes/ (law text, 条旨, guide, structure, official materials), never personal notes.
    for path in sorted((root / 'codes').glob('*/*.json')):
        text.extend(strings(json.loads(path.read_text(encoding='utf-8'))))
    for path in sorted((root / 'src').glob('*.js')):
        text.extend(re.findall(r'[　-〿㐀-鿿＀-￯]+', path.read_text(encoding='utf-8')))
    text.append(''.join(chr(c) for c in range(0x20, 0x7f)))
    text.append('　、。〈〉《》「」『』【】〔〕〖〗—…‘’“”·・；：，．？！（）％＋－／０１２３４５６７８９')
    return ''.join(sorted(set(''.join(text)) - set('\n\r\t')))


def woff2(source, chars):
    options = subset.Options()
    options.flavor = 'woff2'
    options.layout_features = ['*']
    options.name_IDs = ['*']
    options.name_languages = ['*']
    options.notdef_outline = True
    font = TTFont(source)
    subsetter = subset.Subsetter(options)
    subsetter.populate(text=chars)
    subsetter.subset(font)
    out = io.BytesIO()
    font.flavor = 'woff2'
    font.save(out)
    names = {r.nameID: r.toUnicode() for r in font['name'].names if r.platformID == 3}
    return out.getvalue(), names


def main(regular, semibold):
    chars = charset()
    rules = []
    notice = None
    for source, weight in [(regular, 400), (semibold, 600)]:
        data, names = woff2(source, chars)
        notice = notice or names
        rules.append(f'@font-face{{font-family:"Fadian Serif";font-style:normal;font-weight:{weight};font-display:swap;'
                     f'src:url(data:font/woff2;base64,{base64.b64encode(data).decode()}) format("woff2")}}')
        print(f'{Path(source).name}: {len(chars)} characters, {len(data) / 1024:.0f} KB')
    header = (f'/* {notice.get(1, "Noto Serif SC")} subset for 法典笔记. {notice.get(0, "")}\n'
              f'   Licensed under the SIL Open Font License, Version 1.1 ({notice.get(14, "https://openfontlicense.org")}); full text in src/OFL.txt.\n'
              '   Generated by build_font.py; do not edit by hand. */\n')
    (root / 'src/fonts.css').write_text(header + '\n'.join(rules) + '\n', encoding='utf-8')
    # build.py compares the data packs with this list and warns when a later pack needs characters the subset lacks.
    (root / 'src/fonts.chars').write_text(chars, encoding='utf-8')


if __name__ == '__main__':
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(*sys.argv[1:])
